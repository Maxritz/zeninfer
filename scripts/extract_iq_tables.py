"""Extract the GGML IQ grid tables from a fetched ggml-common.h and emit a
self-contained C++ header. The tables are part of the GGML file-format
specification for the I-quant types (they define the lattice codebooks); this
script turns the upstream definition into a C++ table with provenance noted.
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()


def table(name, ctype):
    m = re.search(r'GGML_TABLE_BEGIN\(\w+, ' + name + r',\s*(\w+|#define[^)]*)\)(.*?)GGML_TABLE_END\(\)',
                  src, re.S)
    if not m:
        raise SystemExit(f'table {name} not found')
    body = m.group(2)
    values = re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', body)
    return values


out = []
out.append('// Generated by scripts/extract_iq_tables.py from the GGML format definition')
out.append('// (ggml-common.h, ggml-org/llama.cpp). These grids are part of the GGUF')
out.append('// file-format contract for the I-quant storage types, in the same way the')
out.append('// block byte layouts are; ZenInfer uses them to decode I-quant tensors.')
out.append('#pragma once')
out.append('#include <cstdint>')
out.append('namespace zen::detail {')
out.append('inline constexpr std::uint8_t ksigns_iq2xs[128]={')
v = table('ksigns_iq2xs', 'u8')
assert len(v) == 128, len(v)
out.append(','.join(v) + '};')
out.append('inline constexpr std::uint8_t kmask_iq2xs[8]={1,2,4,8,16,32,64,128};')

for name, ctype, size in (('iq2xxs_grid', 'std::uint64_t', 256),
                          ('iq2xs_grid', 'std::uint64_t', 512),
                          ('iq2s_grid', 'std::uint64_t', 1024),
                          ('iq3xxs_grid', 'std::uint32_t', 256),
                          ('iq3s_grid', 'std::uint32_t', 512),
                          ('iq1s_grid', 'std::uint64_t', 2048)):
    v = table(name, ctype)
    assert len(v) == size, (name, len(v))
    out.append(f'inline constexpr {ctype} {name}[{size}]={{')
    for i in range(0, len(v), 8):
        out.append(','.join(v[i:i + 8]) + ',')
    out[-1] = out[-1][:-1] + '};'
out.append('} // namespace zen::detail')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote {sys.argv[2]}: 128 signs + 6 grids, {sum(len(table(n, None)) for n in ("iq2xxs_grid","iq2xs_grid","iq2s_grid","iq3xxs_grid","iq3s_grid","iq1s_grid"))} grid entries')
