#!/usr/bin/env python3
"""Embed a compiled DXIL blob into a C++ header.

Usage: bin2header.py <input.cso> <output.h> <symbol>

The generated header exposes ``<symbol>`` and ``<symbol>Size`` inside
``namespace zen_dx12_shaders`` so the D3D12 backend can build a compute PSO
without shipping loose .cso files next to the executable.
"""
from __future__ import annotations

import sys


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    source, target, symbol = argv[1], argv[2], argv[3]
    with open(source, "rb") as handle:
        data = handle.read()

    lines = [
        "// Generated by scripts/bin2header.py - do not edit.",
        f"// Source: {source} ({len(data)} bytes)",
        "#pragma once",
        "",
        "namespace zen_dx12_shaders {",
        "",
        f"inline constexpr unsigned char {symbol}[] = {{",
    ]
    for offset in range(0, len(data), 16):
        chunk = ",".join(f"0x{byte:02x}" for byte in data[offset:offset + 16])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        f"inline constexpr unsigned long long {symbol}Size = {len(data)}ULL;",
        "",
        "}  // namespace zen_dx12_shaders",
        "",
    ]

    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
